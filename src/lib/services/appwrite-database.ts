"use client";

import { databases } from "@/lib/appwrite";
import { ID, Query } from "appwrite";
import type {
  CVData,
  UserProfile,
  ApiKey,
  ApiUsageLog,
  JobApplication,
  GeneratedContent,
} from "@/lib/types";

// Environment variables
const DATABASE_ID = process.env.NEXT_PUBLIC_APPWRITE_DATABASE_ID!;
const USERS_COLLECTION_ID =
  process.env.NEXT_PUBLIC_APPWRITE_USERS_COLLECTION_ID!;
const CVS_COLLECTION_ID = process.env.NEXT_PUBLIC_APPWRITE_CVS_COLLECTION_ID!;
const LICENSES_COLLECTION_ID =
  process.env.NEXT_PUBLIC_APPWRITE_LICENSES_COLLECTION_ID!;
const API_KEYS_COLLECTION_ID =
  process.env.NEXT_PUBLIC_APPWRITE_API_KEYS_COLLECTION_ID!;
const API_USAGE_LOGS_COLLECTION_ID =
  process.env.NEXT_PUBLIC_APPWRITE_API_USAGE_LOGS_COLLECTION_ID!;
const JOB_APPLICATIONS_COLLECTION_ID =
  process.env.NEXT_PUBLIC_APPWRITE_JOB_APPLICATIONS_COLLECTION_ID!;

// Constants
const DEFAULT_CV_LIMIT = 3;
const MAX_API_CALLS_PER_MONTH = 500;

/**
 * Appwrite Database Service
 * Handles all database operations using Appwrite
 */
export class AppwriteDatabaseService {
  private userId: string;

  constructor(userId: string) {
    this.userId = userId;
  }

  // ==================== USER PROFILE METHODS ====================

  /**
   * Get or create user profile
   * @param firebaseUser - Optional Firebase user object to get email from
   */
  async getUserProfile(firebaseUser?: any): Promise<UserProfile> {
    try {
      // Try to get existing user by document ID (which is the Firebase userId)
      try {
        const doc = await databases.getDocument(
          DATABASE_ID,
          USERS_COLLECTION_ID,
          this.userId
        );
        return this.mapDocumentToUserProfile(doc);
      } catch (error: any) {
        // If user doesn't exist, create new profile
        if (error.code === 404 || error.message?.includes("not found")) {
          // Check if this is the admin user
          const adminEmail =
            process.env.NEXT_PUBLIC_ADMIN_EMAIL || "amabdo30@gmail.com";
          const isAdminUser = this.userId === process.env.NEXT_PUBLIC_ADMIN_ID; // Your Firebase UID

          // Get email from Firebase user or use admin email
          const userEmail =
            firebaseUser?.email || (isAdminUser ? adminEmail : null);

          if (!userEmail) {
            throw new Error("User email is required to create profile");
          }

          const newUser = await databases.createDocument(
            DATABASE_ID,
            USERS_COLLECTION_ID,
            this.userId, // Use Firebase userId as document ID
            {
              email: userEmail,
              name: isAdminUser ? "Admin" : firebaseUser?.displayName || "",
              phone: "",
              summary: "",
              experience: "",
              education: "",
              skills: "",
              isAdmin: isAdminUser,
              isLicensed: false,
              cvCount: 0,
              cvLimit: isAdminUser ? 100 : DEFAULT_CV_LIMIT, // Give admin higher limit
              apiUsageCount: 0,
              // $createdAt and $updatedAt are auto-generated by Appwrite
            }
          );

          console.log(
            isAdminUser
              ? "✅ Admin user created automatically!"
              : "✅ User created"
          );
          return this.mapDocumentToUserProfile(newUser);
        }
        throw error;
      }
    } catch (error) {
      console.error("Error getting user profile:", error);
      throw error;
    }
  }

  /**
   * Update user profile
   */
  async updateUserProfile(profile: Partial<UserProfile>): Promise<void> {
    try {
      await databases.updateDocument(
        DATABASE_ID,
        USERS_COLLECTION_ID,
        this.userId, // Document ID is the Firebase userId
        {
          ...profile,
          // $updatedAt is auto-generated by Appwrite
        }
      );
    } catch (error) {
      console.error("Error updating user profile:", error);
      throw error;
    }
  }

  // ==================== CV METHODS ====================

  /**
   * Save CV data
   */
  async saveCVData(
    cvData: Omit<CVData, "id" | "userId" | "createdAt" | "updatedAt">
  ): Promise<string> {
    try {
      // Check CV limit
      const profile = await this.getUserProfile();
      const currentCVs = await this.getAllCVs();

      if (currentCVs.length >= (profile.cvLimit || DEFAULT_CV_LIMIT)) {
        throw new Error(
          `You have reached the maximum limit of ${
            profile.cvLimit || DEFAULT_CV_LIMIT
          } CVs. Please delete an existing CV to save a new one.`
        );
      }

      // Create CV document
      const cvDoc = await databases.createDocument(
        DATABASE_ID,
        CVS_COLLECTION_ID,
        ID.unique(),
        {
          users: this.userId,
          fileName: cvData.fileName,
          fileId: cvData.fileId || "",
          rawText: cvData.rawText || "",
          structuredData: JSON.stringify(cvData.structuredData || {}),
          profileData: JSON.stringify(cvData.profile || {}),
          // $createdAt and $updatedAt are auto-generated by Appwrite
        }
      );

      // Update CV count
      await this.updateCVCount(currentCVs.length + 1);

      return cvDoc.$id;
    } catch (error) {
      console.error("Error saving CV:", error);
      throw error;
    }
  }

  /**
   * Get all CVs for user
   */
  async getAllCVs(): Promise<CVData[]> {
    try {
      const response = await databases.listDocuments(
        DATABASE_ID,
        CVS_COLLECTION_ID,
        [Query.equal("users", [this.userId]), Query.orderDesc("$createdAt")]
      );

      return response.documents.map((doc) => this.mapDocumentToCVData(doc));
    } catch (error) {
      console.error("Error getting CVs:", error);
      return [];
    }
  }

  /**
   * Get CV by ID
   */
  async getCVById(cvId: string): Promise<CVData | null> {
    try {
      const doc = await databases.getDocument(
        DATABASE_ID,
        CVS_COLLECTION_ID,
        cvId
      );

      if (doc.users !== this.userId) {
        throw new Error("Unauthorized access to CV");
      }

      return this.mapDocumentToCVData(doc);
    } catch (error) {
      console.error("Error getting CV:", error);
      return null;
    }
  }

  /**
   * Delete CV
   */
  async deleteCVData(cvId: string): Promise<void> {
    try {
      const cv = await this.getCVById(cvId);
      if (!cv) {
        throw new Error("CV not found");
      }

      // Delete from Appwrite Storage
      if (cv.fileId) {
        const { deleteCVFile } = await import("@/lib/appwrite");
        await deleteCVFile(cv.fileId);
      }

      // Delete CV document
      await databases.deleteDocument(DATABASE_ID, CVS_COLLECTION_ID, cvId);

      // Update CV count
      const currentCVs = await this.getAllCVs();
      await this.updateCVCount(currentCVs.length);
    } catch (error) {
      console.error("Error deleting CV:", error);
      throw error;
    }
  }

  /**
   * Update CV count in user profile
   */
  private async updateCVCount(count: number): Promise<void> {
    try {
      await databases.updateDocument(
        DATABASE_ID,
        USERS_COLLECTION_ID,
        this.userId, // Document ID is the Firebase userId
        {
          cvCount: count,
          // $updatedAt is auto-generated by Appwrite
        }
      );
    } catch (error) {
      console.error("Error updating CV count:", error);
    }
  }

  // ==================== LICENSE METHODS ====================

  /**
   * Activate license key
   */
  async activateLicense(licenseKey: string): Promise<boolean> {
    try {
      // Find license by key
      const response = await databases.listDocuments(
        DATABASE_ID,
        LICENSES_COLLECTION_ID,
        [Query.equal("key", licenseKey)]
      );

      if (response.documents.length === 0) {
        throw new Error("Invalid license key");
      }

      const license = response.documents[0];

      // Check if already activated
      if (license.activatedBy) {
        throw new Error("This license key has already been activated");
      }

      // Check if active
      if (!license.isActive) {
        throw new Error("This license key has been deactivated");
      }

      // Activate license
      await databases.updateDocument(
        DATABASE_ID,
        LICENSES_COLLECTION_ID,
        license.$id,
        {
          activatedBy: this.userId,
          activatedAt: new Date().toISOString(),
        }
      );

      // Update user profile
      await this.updateUserProfile({
        isLicensed: true,
        licenseKey: licenseKey,
        licenseActivatedAt: new Date().toISOString(),
      });

      return true;
    } catch (error) {
      console.error("Error activating license:", error);
      throw error;
    }
  }

  /**
   * Check license status
   */
  async checkLicenseStatus(): Promise<boolean> {
    try {
      const profile = await this.getUserProfile();
      return profile.isLicensed || false;
    } catch (error) {
      console.error("Error checking license status:", error);
      return false;
    }
  }

  // ==================== API KEY METHODS ====================

  /**
   * Save API key
   */
  async saveApiKey(apiKey: ApiKey): Promise<void> {
    try {
      await databases.createDocument(
        DATABASE_ID,
        API_KEYS_COLLECTION_ID,
        ID.unique(),
        {
          users: this.userId,
          keyHash: apiKey.keyHash,
          keyPreview: apiKey.key.substring(0, 20) + "...",
          isActive: true,
          // $createdAt is auto-generated by Appwrite
        }
      );

      // Update user profile with API key hash
      await this.updateUserProfile({
        apiKeyHash: apiKey.keyHash,
      });
    } catch (error) {
      console.error("Error saving API key:", error);
      throw error;
    }
  }

  /**
   * Get all API keys for user
   */
  async getApiKeys(): Promise<ApiKey[]> {
    try {
      const response = await databases.listDocuments(
        DATABASE_ID,
        API_KEYS_COLLECTION_ID,
        [Query.equal("users", [this.userId]), Query.orderDesc("$createdAt")] // Relation query
      );

      return response.documents.map((doc) => ({
        id: doc.$id,
        userId: doc.users,
        key: doc.keyPreview,
        keyHash: doc.keyHash,
        createdAt: doc.$createdAt,
        lastUsedAt: doc.lastUsedAt,
        isActive: doc.isActive,
      }));
    } catch (error) {
      console.error("Error getting API keys:", error);
      return [];
    }
  }

  /**
   * Deactivate API key
   */
  async deactivateApiKey(apiKeyId: string): Promise<void> {
    try {
      await databases.updateDocument(
        DATABASE_ID,
        API_KEYS_COLLECTION_ID,
        apiKeyId,
        { isActive: false }
      );
    } catch (error) {
      console.error("Error deactivating API key:", error);
      throw error;
    }
  }

  // ==================== API USAGE METHODS ====================

  /**
   * Log API usage
   */
  async logApiUsage(log: ApiUsageLog): Promise<void> {
    try {
      const month = new Date().toISOString().substring(0, 7);

      await databases.createDocument(
        DATABASE_ID,
        API_USAGE_LOGS_COLLECTION_ID,
        ID.unique(),
        {
          users: this.userId,
          endpoint: log.endpoint,
          timestamp: new Date().toISOString(),
          month: month,
          success: log.success,
          errorMessage: log.errorMessage || "",
          ipAddress: log.ipAddress || "",
        }
      );

      // Update usage count
      const profile = await this.getUserProfile();
      const currentMonth = new Date().toISOString().substring(0, 7);

      if (profile.apiUsageMonth === currentMonth) {
        await this.updateUserProfile({
          apiUsageCount: (profile.apiUsageCount || 0) + 1,
        });
      } else {
        // New month, reset count
        await this.updateUserProfile({
          apiUsageMonth: currentMonth,
          apiUsageCount: 1,
        });
      }
    } catch (error) {
      console.error("Error logging API usage:", error);
    }
  }

  /**
   * Get API usage for current month
   */
  async getApiUsageThisMonth(): Promise<number> {
    try {
      const profile = await this.getUserProfile();
      const currentMonth = new Date().toISOString().substring(0, 7);

      if (profile.apiUsageMonth === currentMonth) {
        return profile.apiUsageCount || 0;
      }

      return 0;
    } catch (error) {
      console.error("Error getting API usage:", error);
      return 0;
    }
  }

  /**
   * Check API rate limit
   */
  async checkApiRateLimit(): Promise<boolean> {
    try {
      const usage = await this.getApiUsageThisMonth();
      return usage < MAX_API_CALLS_PER_MONTH;
    } catch (error) {
      console.error("Error checking API rate limit:", error);
      return false;
    }
  }

  // ==================== JOB APPLICATION METHODS ====================

  /**
   * Save job application
   */
  async saveJobApplication(
    application: Omit<
      JobApplication,
      "id" | "userId" | "createdAt" | "updatedAt"
    >
  ): Promise<string> {
    try {
      const doc = await databases.createDocument(
        DATABASE_ID,
        JOB_APPLICATIONS_COLLECTION_ID,
        ID.unique(),
        {
          users: this.userId,
          cvId: application.cvId,
          jobTitle: application.jobTitle,
          company: application.company,
          jobDescription: application.jobDescription || "",
          coverLetter: application.coverLetter || "",
          applicationStatus: application.applicationStatus || "pending",
          // $createdAt and $updatedAt are auto-generated by Appwrite
        }
      );

      return doc.$id;
    } catch (error) {
      console.error("Error saving job application:", error);
      throw error;
    }
  }

  /**
   * Get all job applications for user
   */
  async getAllJobApplications(): Promise<JobApplication[]> {
    try {
      const response = await databases.listDocuments(
        DATABASE_ID,
        JOB_APPLICATIONS_COLLECTION_ID,
        [Query.equal("users", [this.userId]), Query.orderDesc("$createdAt")] // Relation query
      );

      return response.documents.map((doc) => ({
        id: doc.$id,
        userId: doc.users,
        cvId: doc.cvId,
        jobTitle: doc.jobTitle,
        company: doc.company,
        jobDescription: doc.jobDescription,
        coverLetter: doc.coverLetter,
        applicationStatus: doc.applicationStatus,
        createdAt: doc.$createdAt,
        updatedAt: doc.$updatedAt,
      }));
    } catch (error) {
      console.error("Error getting job applications:", error);
      return [];
    }
  }

  /**
   * Get job application by ID
   */
  async getJobApplicationById(
    applicationId: string
  ): Promise<JobApplication | null> {
    try {
      const doc = await databases.getDocument(
        DATABASE_ID,
        JOB_APPLICATIONS_COLLECTION_ID,
        applicationId
      );

      if (doc.users !== this.userId) {
        throw new Error("Unauthorized access to job application");
      }

      return {
        id: doc.$id,
        userId: doc.users,
        cvId: doc.cvId,
        jobTitle: doc.jobTitle,
        company: doc.company,
        jobDescription: doc.jobDescription,
        coverLetter: doc.coverLetter,
        applicationStatus: doc.applicationStatus,
        createdAt: doc.$createdAt,
        updatedAt: doc.$updatedAt,
      };
    } catch (error) {
      console.error("Error getting job application:", error);
      return null;
    }
  }

  /**
   * Update job application
   */
  async updateJobApplication(
    applicationId: string,
    updates: Partial<JobApplication>
  ): Promise<void> {
    try {
      await databases.updateDocument(
        DATABASE_ID,
        JOB_APPLICATIONS_COLLECTION_ID,
        applicationId,
        {
          ...updates,
          // $updatedAt is auto-generated by Appwrite
        }
      );
    } catch (error) {
      console.error("Error updating job application:", error);
      throw error;
    }
  }

  /**
   * Delete job application
   */
  async deleteJobApplication(applicationId: string): Promise<void> {
    try {
      await databases.deleteDocument(
        DATABASE_ID,
        JOB_APPLICATIONS_COLLECTION_ID,
        applicationId
      );
    } catch (error) {
      console.error("Error deleting job application:", error);
      throw error;
    }
  }

  // ==================== GENERATED CONTENT METHODS ====================

  /**
   * Save generated content (tailored CV, cover letter, etc.)
   */
  async saveGeneratedContent(
    content: Omit<GeneratedContent, "id" | "userId" | "createdAt">
  ): Promise<string> {
    try {
      // For now, we'll store generated content in job applications
      // You can create a separate collection if needed
      const applicationId = content.jobApplicationId;

      if (!applicationId) {
        throw new Error("Job application ID is required for generated content");
      }

      // Update the job application with the generated content
      if (content.type === "cover_letter") {
        await this.updateJobApplication(applicationId, {
          coverLetter: content.content,
        });
      }

      return applicationId;
    } catch (error) {
      console.error("Error saving generated content:", error);
      throw error;
    }
  }

  // ==================== HELPER METHODS ====================

  private mapDocumentToUserProfile(doc: any): UserProfile {
    return {
      name: doc.name || "",
      email: doc.email || "",
      phone: doc.phone || "",
      summary: doc.summary || "",
      experience: doc.experience || "",
      education: doc.education || "",
      skills: doc.skills || "",
      isAdmin: doc.isAdmin || false,
      isLicensed: doc.isLicensed || false,
      licenseKey: doc.licenseKey,
      licenseActivatedAt: doc.licenseActivatedAt,
      apiKeyHash: doc.apiKeyHash,
      apiUsage: doc.apiUsageMonth
        ? {
            month: doc.apiUsageMonth,
            count: doc.apiUsageCount || 0,
          }
        : undefined,
      cvCount: doc.cvCount || 0,
      cvLimit: doc.cvLimit || DEFAULT_CV_LIMIT,
    };
  }

  private mapDocumentToCVData(doc: any): CVData {
    return {
      id: doc.$id,
      userId: doc.users,
      fileName: doc.fileName,
      fileId: doc.fileId,
      rawText: doc.rawText,
      structuredData: doc.structuredData
        ? JSON.parse(doc.structuredData)
        : undefined,
      profile: doc.profileData ? JSON.parse(doc.profileData) : undefined,
      createdAt: doc.$createdAt,
      updatedAt: doc.$updatedAt,
    };
  }
}
